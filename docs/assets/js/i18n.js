  /* ---- helpers ---- */
  var STORAGE_KEY = 'klikrekrut_lang';

  function getSavedLang() {
    try { return localStorage.getItem(STORAGE_KEY) || 'id'; }
    catch (e) { return 'id'; }
  }

  function saveLang(locale) {
    try { localStorage.setItem(STORAGE_KEY, locale); } catch (e) {}
  }

  function translate(key, locale) {
    if (locale === 'id') return key; // Indonesian text IS the key
    var dict = translations[locale];
    return (dict && dict[key]) ? dict[key] : key;
  }

  /* ---- apply translations ---- */
  function applyTranslations(locale) {
    // Translate all elements with data-i18n attribute (textContent)
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var el = els[i];
      var key = el.getAttribute('data-i18n');
      el.textContent = translate(key, locale);
    }

    // Update HTML lang attribute
    document.documentElement.lang = locale;

    // Update locale display in navbar
    var localeDisplays = document.querySelectorAll('.lang-locale-display');
    for (var j = 0; j < localeDisplays.length; j++) {
      localeDisplays[j].textContent = locale.toUpperCase();
    }

    // Update active state on language dropdown items
    var langItems = document.querySelectorAll('[data-lang]');
    for (var k = 0; k < langItems.length; k++) {
      var item = langItems[k];
      if (item.getAttribute('data-lang') === locale) {
        item.classList.add('active');
      } else {
        item.classList.remove('active');
      }
    }
  }

  /* ---- public API ---- */
  window.switchLang = function (locale) {
    if (locale !== 'id' && locale !== 'en') return;
    saveLang(locale);
    applyTranslations(locale);

    // Close dropdown menus after switching
    var desktopToggle = document.querySelector('.lang-toggle-desktop');
    if (desktopToggle) desktopToggle.classList.remove('open');
    var mobileToggle = document.getElementById('mobile-lang-toggle');
    if (mobileToggle) mobileToggle.classList.remove('open');
  };

  /* ---- init on DOM ready ---- */
  document.addEventListener('DOMContentLoaded', function () {
    var savedLang = getSavedLang();
    applyTranslations(savedLang);
  });
